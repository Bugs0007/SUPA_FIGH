interface GlyphData {
  x: number;
  y: number;
  width: number;
  height: number;
  centerX: number;
  centerY: number;
  xOffset: number;
  yOffset: number;
  xAdvance: number;
  data: object;
  kerning: object;
  u0: number;
  v0: number;
  u1: number;
  v1: number;
}

function buildFont(scene: Phaser.Scene, key: string, glyphs: Record<string, string>, gh: number, outlined: boolean): void {
  const o = outlined ? 1 : 0;
  const entries = Object.entries(glyphs).map(([ch, s]) => ({ ch, rows: s.split('|') }));
  const maxW = Math.max(...entries.map((e) => e.rows[0].length));
  const cellW = maxW + 2 * o + 1;
  const cellH = gh + 2 * o + 1;
  const cols = 16;
  const texW = cols * cellW;
  const texH = Math.ceil(entries.length / cols) * cellH;
  const pc = new PixelCanvas(texW, texH);
  const chars: Record<number, GlyphData> = {};

  entries.forEach((e, idx) => {
    const cx = (idx % cols) * cellW;
    const cy = Math.floor(idx / cols) * cellH;
    const w = e.rows[0].length;
    for (let y = 0; y < e.rows.length; y++)
      for (let x = 0; x < w; x++) if (e.rows[y][x] === '#') pc.set(cx + o + x, cy + o + y, P.white);
    if (outlined) pc.outline(cx, cy, w + 2, gh + 2, P.ink, true);
    const gw = w + 2 * o;
    const gH = gh + 2 * o;
    chars[e.ch.charCodeAt(0)] = {
      x: cx,
      y: cy,
      width: gw,
      height: gH,
      centerX: gw / 2,
      centerY: gH / 2,
      xOffset: 0,
      yOffset: 0,
      xAdvance: w + 1,
      data: {},
      kerning: {},
      u0: cx / texW,
      v0: cy / texH,
      u1: (cx + gw) / texW,
      v1: (cy + gH) / texH,
    };
  });

  const texKey = 'font_' + key;
  if (scene.textures.exists(texKey)) scene.textures.remove(texKey);
  scene.textures.addCanvas(texKey, pc.flush());
  const data = { font: key, size: gh + 2 * o, lineHeight: gh + 2 * o + 2, chars };
  scene.cache.bitmapFont.add(key, { data, texture: texKey, frame: null });
}

export function buildFonts(scene: Phaser.Scene): void {
  buildFont(scene, 'px', BIG, 7, false);
  buildFont(scene, 'pxo', BIG, 7, true);
  buildFont(scene, 'sm', SMALL, 5, false);
  buildFont(scene, 'smo', SMALL, 5, true);
}

/** Pixel width of a string in a font (for layout without creating objects). */
export function textWidth(text: string, font: 'px' | 'pxo' | 'sm' | 'smo'): number {
  const table = font === 'px' || font === 'pxo' ? BIG : SMALL;
  let w = 0;
  for (const ch of text.toUpperCase()) {
    const g = table[ch] ?? table[' '];
    w += g.split('|')[0].length + 1;
  }
  return Math.max(0, w - 1) + (font.endsWith('o') ? 2 : 0);
}
