# Map builder for SCRAPYARD RIOT. Emits src/sim/map/maps/<id>.ts (ASCII rows + gimmicks).
import json, sys
import os
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'sim', 'map', 'maps') + os.sep

class G:
    def __init__(s, w, h, fill='.'):
        s.w, s.h = w, h
        s.g = [[fill] * w for _ in range(h)]
    def p(s, x, y, c):
        if 0 <= x < s.w and 0 <= y < s.h: s.g[y][x] = c
    def get(s, x, y):
        return s.g[y][x] if 0 <= x < s.w and 0 <= y < s.h else '.'
    def rect(s, x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1): s.p(x, y, c)
    def hl(s, x0, x1, y, c): s.rect(x0, y, x1, y, c)
    def vl(s, x, y0, y1, c): s.rect(x, y0, x, y1, c)
    def back(s, x0, y0, x1, y1):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if s.get(x, y) == '.': s.p(x, y, ':')
    def ladder(s, x, y0, y1):
        """ladder column from y0 (top cell, usually the platform row) down to y1 (cell above the floor)"""
        s.vl(x, y0, y1, 'H')
    def mark(s, x, floor_y, c):
        """put a marker standing on the floor row floor_y (nudged sideways if the cell is taken)"""
        for dx in [0, 1, -1, 2, -2, 3, -3, 4, -4]:
            xx = x + dx
            if s.get(xx, floor_y - 1) in '.:' and s.get(xx, floor_y - 2) in '.:' and s.get(xx, floor_y) not in '.:~':
                if dx: print('  nudged', c, x, '->', xx, 'row', floor_y)
                s.p(xx, floor_y - 1, c)
                return
        raise AssertionError(('no room for marker', c, x, floor_y))
    def rows(s):
        return [''.join(r) for r in s.g]

def emit(var, mid, name, theme, blurb, g, gimmicks=None, kill=48):
    rows = g.rows()
    n = sum(r.count('S') for r in rows)
    assert n == 10, (mid, 'spawns', n)
    lines = [f"import type {{ MapDef }} from '../mapData';", '', f'// Generated by the map builder, then hand-tuned. {blurb}',
             f'export const {var}: MapDef = {{', f"  id: '{mid}',", f"  name: '{name}',", f"  theme: '{theme}',", f"  blurb: '{blurb}',", f'  killMargin: {kill},', '  rows: [']
    for i, r in enumerate(rows): lines.append(f"    '{r}', // {i}")
    lines.append('  ],')
    if gimmicks:
        lines.append('  gimmicks: ' + json.dumps(gimmicks, indent=2).replace('\n', '\n  ').replace('"', "'") + ',')
    lines.append('};')
    open(OUT + mid + '.ts', 'w').write('\n'.join(lines) + '\n')
    print(mid, g.w, 'x', g.h)

